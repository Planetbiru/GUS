// ----------------------------------------------------------------
// 1.1  GUSPatchGenerator — utilitas matematika waveform & DSP
// ----------------------------------------------------------------
class GUSPatchGenerator {
    static TAU = Math.PI * 2;

    static sin(p) {
        return Math.sin(Math.PI * 2 * p);
    }

    static partials(phase, amps) {
        let s = 0;
        for (let k = 0; k < amps.length; k++) s += amps[k] * Math.sin(Math.PI * 2 * phase * (k + 1));
        return s;
    }

    static normalize(buffer, target = 0.9) {
        let peak = 0;
        for (let i = 0; i < buffer.length; i++) {
            const a = Math.abs(buffer[i]);
            if (a > peak) peak = a;
        }
        if (peak > 0) {
            const k = target / peak;
            for (let i = 0; i < buffer.length; i++) buffer[i] *= k;
        }
    }

    static fadeOut(buffer, fadeLen) {
        const L = buffer.length;
        for (let i = 0; i < fadeLen; i++) buffer[L - 1 - i] *= i / fadeLen;
    }

    static highpass(buffer, cutoff, SR) {
        const rc = 1 / (2 * Math.PI * cutoff);
        const dt = 1 / SR;
        const a = rc / (rc + dt);
        let pi = 0, po = 0;
        for (let i = 0; i < buffer.length; i++) {
            const x = buffer[i];
            const y = a * (po + x - pi);
            pi = x; po = y;
            buffer[i] = y;
        }
    }

    static lowpass(buffer, cutoff, SR) {
        const rc = 1 / (2 * Math.PI * cutoff);
        const dt = 1 / SR;
        const a = dt / (rc + dt);
        let prev = 0;
        for (let i = 0; i < buffer.length; i++) {
            prev += a * (buffer[i] - prev);
            buffer[i] = prev;
        }
    }
}

// ----------------------------------------------------------------
// 1.2  GusPatchEncoder — membungkus PCM ke file .pat GUS
// ----------------------------------------------------------------
class GusPatchEncoder {
    static encode({ name, pcm, loopStart, loopEnd, isLoop, rootFreq, sampleRate }) {
        const SR = sampleRate || 22050;
        const periodNs = Math.round(1e9 / SR);

        const instSize = 47 + 63 + pcm.length;
        const dataSize = 63 + instSize;
        const buf = new ArrayBuffer(128 + dataSize);
        const view = new DataView(buf);
        const bytes = new Uint8Array(buf);
        let off = 0;

        const str = (s, n) => { for (let i = 0; i < n; i++) bytes[off++] = i < s.length ? s.charCodeAt(i) & 0x7f : 0; };
        const u8 = v => { bytes[off++] = v & 0xff; };
        const u16 = v => { view.setUint16(off, v, true); off += 2; };
        const u32 = v => { view.setUint32(off, v, true); off += 4; };
        const zeros = n => { for (let i = 0; i < n; i++) bytes[off++] = 0; };

        // Main Header (128 byte)
        str('GF1PATCH110', 12);
        str('ID#000002', 10);
        str('Generated by JS oscillators', 60);
        u8(1); u8(1); u8(1); u16(1); u8(100);
        u32(dataSize);
        zeros(36);

        // Instrument Header (63 byte)
        u16(0);
        str(name, 16);
        u32(instSize);
        u8(1);
        zeros(40);

        // Layer Header (47 byte)
        u8(0); u8(0);
        u32(63 + pcm.length);
        u8(1);
        zeros(40);

        // Sample Header (63 byte)
        str(name.slice(0, 7), 7);
        u8(0);
        u32(pcm.length);
        u32(isLoop ? loopStart : 0);
        u32(isLoop ? loopEnd : 0);
        u16(periodNs);
        u32(rootFreq); u32(rootFreq); u32(rootFreq);
        u16(0);
        u8(7);
        u8(0x00); u8(0xFF);
        u8(0); u8(0); u8(0); u8(0); u8(0); u8(0);
        u8(0); u8(0); u8(0); u8(0); u8(0); u8(0);
        u8(0); u8(0); u8(0);
        u8(0); u8(0); u8(0);
        u8(isLoop ? 0x01 : 0x09);
        zeros(7);

        // Sample data (8-bit signed)
        for (let i = 0; i < pcm.length; i++) {
            const v = Math.max(-128, Math.min(127, Math.round(pcm[i] * 127)));
            bytes[off++] = v & 0xff;
        }
        return buf;
    }
}

// ----------------------------------------------------------------
// 1.3  MelodicRenderer — render preset melodis → PCM
// ----------------------------------------------------------------
class MelodicRenderer {
    constructor(preset, override = {}) {
        this.p = preset;
        this.o = override;
        this.SR = override.sampleRate || preset.sampleRate || 22050;
        this.isLoop = preset.loop && !override.forceNoLoop;
    }

    render() {
        const { p, o, SR, isLoop } = this;

        // --- Tentukan panjang & frekuensi dasar ---
        let length, baseFreq, loopStart = 0, loopEnd = 0, cs = 50;
        if (isLoop) {
            cs = p.cycleSamples || 50;
            const cycles = p.cycles || 12;
            length = cs * cycles;
            baseFreq = o.freq || SR / cs;
            loopStart = (p.loopSkip || 3) * cs;
            loopEnd = length;
        } else {
            length = p.length || Math.round(SR * (o.duration || 0.25));
            baseFreq = o.freq || p.freq || 441;
        }

        // --- Modulasi: matikan vibrato & detune saat loop ---
        const vib = isLoop ? null : (p.vibrato || null);
        const detunes = isLoop ? [0] : (p.detune || [0]);

        const env = p.env || { a: 0.005, d: 0.5, s: 0, r: 0.3 };
        const noiseAmt = p.noise || 0;
        const fm = p.fm || null;
        const harm = p.harm || [1];

        const voices = detunes.map(c => ({ phase: 0, ratio: Math.pow(2, c / 1200) }));
        const out = new Float32Array(length);

        // --- Noise periodik untuk loop ---
        const noiseBuf = (isLoop && noiseAmt > 0) ? this._buildLoopNoise(cs) : null;
        const fadeSamples = isLoop ? cs : 0;

        // --- Render loop sample ---
        for (let i = 0; i < length; i++) {
            const t = i / SR;
            const vDepth = vib ? vib.depth * Math.sin(Math.PI * 2 * vib.rate * t) : 0;
            let sample = 0;

            for (const v of voices) {
                const f = baseFreq * v.ratio * (1 + vDepth);
                if (fm) {
                    const mod = Math.sin(Math.PI * 2 * f * fm.ratio * t) * fm.index;
                    sample += Math.sin(Math.PI * 2 * f * t + mod);
                } else {
                    v.phase += f / SR;
                    sample += GUSPatchGenerator.partials(v.phase, harm);
                }
            }
            sample /= voices.length;

            if (noiseAmt > 0) {
                const n = noiseBuf ? noiseBuf[i % cs] : (Math.random() * 2 - 1);
                sample = sample * (1 - noiseAmt) + n * noiseAmt;
            }

            out[i] = sample * this._envelope(t, length, env, isLoop, i, fadeSamples);
        }

        GUSPatchGenerator.normalize(out, 0.9);
        return { pcm: out, length, loopStart, loopEnd, loop: isLoop, SR };
    }

    _envelope(t, length, env, isLoop, i, fadeSamples) {
        if (isLoop) return i < fadeSamples ? (i / fadeSamples) : 1.0;

        let e;
        if (t < env.a) e = t / env.a;
        else if (t < env.a + env.d) e = 1 - (1 - env.s) * ((t - env.a) / env.d);
        else e = env.s;

        if (env.r > 0) {
            const relStart = length / this.SR - env.r;
            if (t > relStart) e *= Math.max(0, 1 - (t - relStart) / env.r);
        }
        return e;
    }

    _buildLoopNoise(cs) {
        let buf = new Float32Array(cs);
        for (let i = 0; i < cs; i++) buf[i] = Math.random() * 2 - 1;
        for (let pass = 0; pass < 2; pass++) {
            const tmp = new Float32Array(cs);
            for (let i = 0; i < cs; i++) {
                tmp[i] = (buf[(i - 1 + cs) % cs] + 2 * buf[i] + buf[(i + 1) % cs]) / 4;
            }
            buf = tmp;
        }
        let np = 0;
        for (let i = 0; i < cs; i++) np = Math.max(np, Math.abs(buf[i]));
        if (np > 0) for (let i = 0; i < cs; i++) buf[i] /= np;
        return buf;
    }
}

