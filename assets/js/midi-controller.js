  static async createMidiDemoProject(buttons, projectName){
    
    if(isDemoGenerating) return;
    isDemoGenerating = true;
    buttons.forEach(button=>button.disabled=true);
    
    const melodicBank = 0; // Default melodic bank

    try{
      if(!projectPatchGenerator)projectPatchGenerator=new ProjectPatchGenerator();
      const melodic=projectPatchGenerator.getPrograms(false);
      const drums=projectPatchGenerator.getPrograms(true);
      if(melodic.length!==128 || drums.length===0){
        throw new Error("The demo instrument library is incomplete.");
      }
  
      const project={
        id:uid("demo-project"),
        name:projectName || t("demo_project_name"),
        patchIds:[],
        demoGenerated:true
      };
  
      const existingPatches=getProjectPatches(project);
      const tasks=[
        ...melodic.map(instrument=>({instrument, isDrum:false, bank:melodicBank})),
        ...drums.map(instrument=>({instrument, isDrum:true, bank:128}))
      ];
      const melodicPitchRanges=[
        {pitchFrom:0,pitchTo:47},
        {pitchFrom:48,pitchTo:59},
        {pitchFrom:60,pitchTo:71},
        {pitchFrom:72,pitchTo:83},
        {pitchFrom:84,pitchTo:95},
        {pitchFrom:96,pitchTo:127}
      ];
      const hasCompleteMelodicPitchCoverage=entry=>{
        const samples=entry.patch.instruments.flatMap(inst=>
          inst.layers.flatMap(layer=>layer.samples)
        );
        if(samples.length!==melodicPitchRanges.length)return false;
        const ranges=samples.map(sample=>({
          from:sample._generatorInfo?.pitchFrom
            ?? ProjectPatchGenerator.frequencyToMidiPitch(sample.lowFreq),
          to:sample._generatorInfo?.pitchTo
            ?? ProjectPatchGenerator.frequencyToMidiPitch(sample.highFreq)
        })).sort((a,b)=>a.from-b.from);
        let nextPitch=0;
        for(const range of ranges){
          if(!Number.isInteger(range.from)||!Number.isInteger(range.to)
            ||range.from!==nextPitch||range.to<range.from||range.to>127)return false;
          nextPitch=range.to+1;
        }
        return nextPitch===128;
      };
      const missingTasks=tasks.flatMap(task=>{
        const existingPatch=existingPatches.find(entry=>
          (entry.gmBank===128 ? 128 : 0)===task.bank
          && entry.gmProgram===task.instrument.id
        );
        if(!existingPatch)return [{...task,existingPatch:null}];
        if(!task.isDrum
          && existingPatch.source==="demo-generated"
          && !hasCompleteMelodicPitchCoverage(existingPatch)){
          return [{...task,existingPatch}];
        }
        return [];
      });
  
      if(missingTasks.length===0){
        throw new Error("No demo instruments were generated.");
      }
  
      const entries=[];
      let completed=tasks.length-missingTasks.length;

      // Default waveform for each instrument: ('sine', 'triangle', 'square' or 'saw')
      const defaultWaveform = {
        "0"  : "saw", // Acoustic Grand Piano use saw for demo
        "24" : "saw", // Nylon Guitar
        "25" : "saw", // Steel Guitar
      };
      
      showStatus(t("demo_generation_progress",{completed,total:tasks.length}));
      for(let index=0;index<missingTasks.length;index++){
        const {instrument,isDrum,bank}=missingTasks[index];
        const pitchRanges=isDrum
          ? [{pitchFrom:0,pitchTo:127}]
          : melodicPitchRanges;
        const generatedSamples=[];
        let generated;

        for(const [sampleIndex,pitchRange] of pitchRanges.entries()){
          const result=projectPatchGenerator.generate({
            isDrum,
            program:instrument.id,
            waveform:defaultWaveform[instrument.id] || null,
            ...pitchRange
          });
          if(!generated)generated=result;
          const sample=result.patch.instruments[0].layers[0].samples[0];
          if(!isDrum){
            sample.name=`${sample.name.slice(0,5)}${String(sampleIndex+1).padStart(2,"0")}`;
          }
          const originalSample=cleanSampleForStorage(sample);
          sample._autoGenerated=true;
          sample._generatorInfo={
            isDrum:!!isDrum,
            program:instrument.id,
            waveform:null,
            pitchFrom:result.pitchFrom,
            pitchTo:result.pitchTo,
            originalSample
          };
          generatedSamples.push(sample);
        }
        generated.patch.instruments[0].layers[0].samples=generatedSamples;
        entries.push({
          ...(missingTasks[index].existingPatch || {}),
          id:missingTasks[index].existingPatch?.id || uid("demo-patch"),
          name:generated.name,
          source:"demo-generated",
          gmProgram:generated.program,
          gmBank:bank,
          ...(isDrum ? {drumSet:0} : {}),
          patch:generated.patch
        });
        completed++;
        if((index+1)%2===0 || index===missingTasks.length-1){
          showStatus(t("demo_generation_progress",{
            completed,
            total:tasks.length
          }));
          await new Promise(resolve=>setTimeout(resolve,0));
        }
      }
  
      const updatedProject={
        ...project,
        patchIds:[...new Set([...(project.patchIds||[]),...entries.map(entry=>entry.id)])],
        demoGenerated:true
      };
      await dbSaveProjectAndPatches(updatedProject,entries);
      state.projects.push(updatedProject);
      const updatedEntries=new Map(entries.map(entry=>[entry.id,entry]));
      state.patches=state.patches.map(entry=>updatedEntries.get(entry.id)||entry);
      const currentPatchIds=new Set(state.patches.map(entry=>entry.id));
      state.patches.push(...entries.filter(entry=>!currentPatchIds.has(entry.id)));
      selectProject(updatedProject.id);
      if(entries.length>0)selectPatch(entries[0].id);
      showStatus(t("demo_project_ready",{count:tasks.length}),"ok");
    }catch(err){
      console.error("Demo project generation failed:",err);
      showStatus(t("demo_generation_failed",{message:err.message}),"bad");
    }finally{
      isDemoGenerating=false;
      buttons.forEach(button=>button.disabled=false);
    }
  }

